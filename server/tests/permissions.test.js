import test from 'node:test';
import assert from 'node:assert/strict';
import { mayReadTicket, mayEditTicketFields, mayArchiveTicket, mayViewArchive, mayApproveTicket, ticketScope } from '../src/domain/permissions.js';
const agent = { _id: 'user-1', role: 'agent' };
const manager = { _id: 'user-9', role: 'manager' };
const ticket = { assignedTo:'user-1', status:'open', archivedAt:null };
test('assigned agent can read own ticket', () => assert.equal(mayReadTicket(ticket,agent),true));
test('other agent cannot read ticket', () => assert.equal(mayReadTicket(ticket,{...agent,_id:'user-2'}),false));
test('manager can read active ticket', () => assert.equal(mayReadTicket(ticket,manager),true));
test('archived tickets hidden in standard view', () => assert.equal(mayReadTicket({...ticket,archivedAt:new Date()},manager),false));
test('manager can inspect archived ticket read-only', () => assert.equal(mayReadTicket({...ticket,archivedAt:new Date()},manager,{allowArchived:true}),true));
test('agents can never inspect archived ticket', () => assert.equal(mayReadTicket({...ticket,archivedAt:new Date()},agent,{allowArchived:true}),false));
test('manager can open archive register', () => assert.equal(mayViewArchive(manager),true));
test('agents cannot access archive register', () => assert.equal(mayViewArchive(agent),false));
test('manager archive scope excludes all active tickets', () => assert.deepEqual(ticketScope(manager,{archivedOnly:true}),{archivedAt:{$ne:null}}));
test('default manager scope contains only current records', () => assert.deepEqual(ticketScope(manager),{archivedAt:null}));
test('agent scope restricts to own current tickets', () => assert.deepEqual(ticketScope(agent),{archivedAt:null,assignedTo:'user-1'}));
test('agent cannot request archive scope', () => assert.throws(()=>ticketScope(agent,{archivedOnly:true}),/Only managers/));
test('agent can update status only', () => assert.equal(mayEditTicketFields(agent,{status:'resolved'}),true));
test('agent cannot change ticket priority', () => assert.equal(mayEditTicketFields(agent,{priority:'critical'}),false));
test('manager can change ticket priority', () => assert.equal(mayEditTicketFields(manager,{priority:'critical'}),true));
test('manager may archive resolved ticket', () => assert.equal(mayArchiveTicket({...ticket,status:'resolved'},manager),true));
test('manager cannot archive unresolved ticket', () => assert.equal(mayArchiveTicket(ticket,manager),false));
test('agent cannot archive ticket', () => assert.equal(mayArchiveTicket({...ticket,status:'resolved'},agent),false));
test('agent cannot approve or reject ticket', () => {
  assert.equal(mayApproveTicket(agent), false);
  assert.equal(mayEditTicketFields(agent, { approvalStatus: 'approved' }), false);
  assert.equal(mayEditTicketFields(agent, { approvalStatus: 'rejected' }), false);
});
test('manager can approve or reject ticket', () => {
  assert.equal(mayApproveTicket(manager), true);
  assert.equal(mayEditTicketFields(manager, { approvalStatus: 'approved' }), true);
  assert.equal(mayEditTicketFields(manager, { approvalStatus: 'rejected' }), true);
});
